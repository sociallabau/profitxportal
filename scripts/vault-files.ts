// Writes supabase/functions/_shared/vaultFiles.ts from src/data/vault.ts.
// Run after editing the Vault: npx tsx scripts/vault-files.ts
import { writeFileSync } from 'node:fs';
import { vaultFiles } from '../src/data/vault';

export const vaultFilesSource = () =>
  `// Generated by scripts/vault-files.ts from src/data/vault.ts. Don't edit by hand.\nexport const VAULT_FILES: { title: string; date: string | null; drive: string[]; fathom: string[]; notion: { host: string; id: string }[] }[] = ${JSON.stringify(vaultFiles(), null, 2)};\n`;

if (process.argv[1]?.endsWith('vault-files.ts')) writeFileSync('supabase/functions/_shared/vaultFiles.ts', vaultFilesSource());
